/** Condition object factory — open box and refurb priced as a percentage off. */
function conditions(base, stock = 8, compareAt = 0) {
  return {
    new: { price: base, compareAtPrice: compareAt || 0, stock },
    openBox: { price: Math.round((base * 0.92) / 500) * 500, compareAtPrice: base, stock: Math.max(2, Math.round(stock * 0.6)) },
    refurb: { price: Math.round((base * 0.82) / 500) * 500, compareAtPrice: base, stock: Math.max(1, Math.round(stock * 0.4)) },
  };
}

function mk({ id, name, brand, category, art, tone = "graphite", accent = "#0062ff", shortSpec, description, price, compareAt, stock = 8, storage = [], ram = [], colors = [], specs = {}, badges = [], rating = 4.7, reviewCount = 120, tags = [], featured = false, flash = false, flashHours = 9, createdAt }) {
  return {
    id,
    name,
    slug: id,
    brand,
    category,
    art,
    tone,
    accent,
    shortSpec,
    description,
    conditions: conditions(price, stock, compareAt),
    variants: { storage, ram, color: colors },
    specs,
    images: [],
    badges,
    tags,
    rating,
    reviewCount,
    isFlashDeal: flash,
    flashEndsAt: flash ? Date.now() + flashHours * HOURS : null,
    isFeatured: featured,
    isActive: true,
    createdAt: createdAt || Date.now() - 30 * DAYS,
    searchKeywords: `${name} ${brand} ${category} ${shortSpec}`.toLowerCase(),
  };
}

