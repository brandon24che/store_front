let current = readStoredLang();
const listeners = new Set();

function readStoredLang() {
  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === "en" || stored === "fr" ? stored : "fr";
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  const table = dict[current] || dict.fr;
  let value = table[key] ?? dict.fr[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, replacement);
    }
  }
  return value;
}

export function setLang(lang) {
  if (lang !== "fr" && lang !== "en") return;
  current = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  applyTranslations(document);
  listeners.forEach((fn) => fn(lang));
  window.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

export function toggleLang() {
  setLang(current === "fr" ? "en" : "fr");
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Applies data-i18n attributes inside a root element. */
export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((node) => {
    node.innerHTML = t(node.dataset.i18nHtml);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAria));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.setAttribute("title", t(node.dataset.i18nTitle));
  });
  document.documentElement.lang = current;
}

/** Resolves a bilingual object such as { fr, en } or returns the raw string. */
export function localized(value) {
  if (value && typeof value === "object" && (value.fr || value.en)) {
    return value[current] ?? value.fr;
  }
  return value;
}

/** Short currency/date locale for Intl calls. */
export const locale = () => APP.locale[current] || "fr-CM";

